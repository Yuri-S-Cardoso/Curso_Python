# if / elif / else
# se / se não se / se não

condicao1 = False
condicao2 = False
condicao3 = True
condicao4 = False

if condicao1:
    print('Códgio para condição 1')
elif condicao2:
    print('Códgio para condição 2')
elif condicao3:
    print('Códgio para condição 3')
elif condicao4:
    print('Códgio para condição 4')
else:
    print('Nenhuma condição foi satisfeita')

