"""
Python = Linguagem de programação
Tipo de tipagem = Dinâmica / Forte
str -> string -> texto
Strings são textos que estão dentro de aspas
"""

# Aspas simples
print('Aspas simples')

#Aspas duplas
print("Duplas aspas")

#Escape
print("Escape \" escape\"")

# r (expressão regulares)
print(r"Escape \" escape\"")

# Para o código ficar limpo pode realizar o print com aspas simples e o que for para ser colocar em aspas, use aspas duplas
print('Aspas "Aspas"')
#ou ao contrário
print("Aspas 'Aspas'")