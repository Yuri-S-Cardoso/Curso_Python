# Tipos int e float
# int -> Número inteiro
# O tipo int represnta qualquer número
# positivo ou negativo. int sem sinal é consideado positivo

print(-11)
print(0)
print(11)

# float -> Número com ponto flutuante
# O tipo float representa qualquer número positivo ou
# negativo com ponto flutuante.
# float sem sinal é cnsiderado positivo

print(1.1) # Na programação sempre utilizará o ponto para separar as casas decimais
print(2.2, 5.5)
print(0.0, -1.5)

# A função(class) type mostra o tipo que o Python inferiu ao valor.
print(type(1))
print(type(2.2))
print(type('Oi'))
